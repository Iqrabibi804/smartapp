  static List<PunjabCity> search(String query) {
    if (query.trim().isEmpty) return allCities;
    final q = query.toLowerCase().trim();
    return allCities.where((c) {
      return c.name.toLowerCase().contains(q) ||
          c.urduName.contains(q) ||
          c.district.toLowerCase().contains(q) ||
          c.region.toLowerCase().contains(q) ||
          c.tagline.toLowerCase().contains(q);
    }).toList();
  }

  static PunjabCity getById(String id) {
    return allCities.firstWhere(
      (c) => c.id.toLowerCase() == id.toLowerCase(),
      orElse: () => allCities.first,
    );
  }
