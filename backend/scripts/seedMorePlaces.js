async function seedMore() {
  await mongoose.connect(process.env.MONGO_URI || 'mongodb://127.0.0.1:27017/smartmap_ai');
  const categories = await Category.find();
  const catMap = {};
  categories.forEach(c => catMap[c.name] = c._id);

  for (const p of MORE_PLACES) {
    const catId = catMap[p.categoryName];
    if (!catId) continue;
    const existing = await Place.findOne({ name: p.name });
    if (!existing) {
      await Place.create({
        name: p.name,
        description: p.description,
        region: p.region,
        categoryId: catId,
        location: p.location,
        address: p.address,
        priceRange: p.priceRange,
        rating: p.rating,
        reviewCount: p.reviewCount,
        verified: p.verified,
        featured: p.featured,
        facilities: p.facilities,
        phone: p.phone,
        images: p.images,
      });
      console.log(`+ Added: [${p.categoryName}] ${p.name}`);
    }
  }

  console.log('Done!');
  process.exit(0);
}

seedMore().catch(err => {
  console.error(err);
  process.exit(1);
});
